// Icons are decorative: the name next to them carries the meaning.
const svg = (icon) => createElement(icon, { 'aria-hidden': 'true' });

export const lockIcon = () => svg(Lock);
const UI = { star: Star, history: History, sun: Sun, moon: Moon };
export const uiIcon = (name) => svg(UI[name]);
export const categoryIcon = (id) => svg(CATEGORY[id]);
/** A tool's own icon, or its category's when it has none. */
export const toolIcon = (tool) => svg(TOOL[tool.id] || CATEGORY[tool.cat]);
